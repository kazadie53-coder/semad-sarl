CREATE OR REPLACE FUNCTION public.erp_verifier_article_catalogue() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$ BEGIN IF NEW.code_article IS NOT NULL THEN SELECT designation INTO NEW.designation FROM public.erp_catalogue WHERE code=NEW.code_article AND actif; IF NOT FOUND THEN RAISE EXCEPTION 'Code article inconnu ou inactif'; END IF; END IF; RETURN NEW; END; $$;
DROP TRIGGER IF EXISTS erp_article_catalogue ON public.erp_articles;
CREATE TRIGGER erp_article_catalogue BEFORE INSERT OR UPDATE OF code_article,designation ON public.erp_articles FOR EACH ROW EXECUTE FUNCTION public.erp_verifier_article_catalogue();
REVOKE ALL ON FUNCTION public.erp_verifier_article_catalogue() FROM PUBLIC;
